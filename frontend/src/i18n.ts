const DICTS: Record<Lang, Partial<Record<string, string>>> = { zh, en }

/** 登录页的随机用户名建议。英文形容词带尾随空格：拼接处不加分隔符。 */
const NAME_PARTS: Record<Lang, { adjectives: string[]; creatures: string[] }> = {
  zh: {
    adjectives: ['勤奋的', '好奇的', '专注的', '沉稳的', '敏捷的', '踏实的', '爱问的', '安静的'],
    creatures: ['水獺', '猫头鹰', '小海豹', '刺猬', '树懒', '狐狸', '柯基', '企鹅'],
  },
  en: {
    adjectives: ['Diligent ', 'Curious ', 'Focused ', 'Steady ', 'Nimble ', 'Grounded ', 'Inquisitive ', 'Quiet '],
    creatures: ['Otter', 'Owl', 'Seal', 'Hedgehog', 'Sloth', 'Fox', 'Corgi', 'Penguin'],
  },
}

let current: Lang = read()

/** 首次访问一律中文，不读 navigator.language。 */
function read(): Lang {
  try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh' } catch { return 'zh' }
}

function applyDocumentLang() {
  if (typeof document !== 'undefined') document.documentElement.lang = current === 'en' ? 'en' : 'zh-CN'
}
applyDocumentLang()

export function getLang(): Lang { return current }

/** 模块变量与 <html lang> 一起更新。界面重渲染由 LangContext 那边的 state 负责。 */
export function setLang(next: Lang) {
  current = next
  try { localStorage.setItem(STORAGE_KEY, next) } catch { /* 隐私模式下写不进，语言只在本次会话有效 */ }
  applyDocumentLang()
}

export function nameParts() { return NAME_PARTS[current] }

/** 日期时间格式化用的 locale。注意 `toLocaleDateString('sv')` 是拿来当 YYYY-MM-DD 用的，别改成这个。 */
export function locale(): string { return current === 'en' ? 'en-US' : 'zh-CN' }

function fill(template: string, args?: Args): string {
  return args ? template.replace(/\{(\w+)\}/g, (whole, name) => (name in args ? String(args[name]) : whole)) : template
}

/** n === 1 时优先取单数条目，没写就退回主条目。 */
function lookup(key: string, args?: Args): string | undefined {
  const dict = DICTS[current]
  if (args?.n === 1) {
    const one = dict[`${key}.one`]
    if (one !== undefined) return one
  }
  return dict[key]
}

export function t(key: TKey, args?: Args): string {
  return fill(lookup(key, args) ?? key, args)
}

/** 动态 key（后端给的 summary_key、工具名、任务阶段）：字典里没有就用 fallback，
 *  不能把 `summary.foo_bar` 这种原始 key 显示到界面上。 */
export function tOr(key: string, fallback: string, args?: Args): string {
  return fill(lookup(key, args) ?? fallback, args)
}

export const LangContext = createContext<{ lang: Lang; setLang: (next: Lang) => void }>({ lang: 'zh', setLang })

export function useI18n() { return useContext(LangContext) }
